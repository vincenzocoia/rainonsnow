# ---------------------------------------------------------------------------
# A grafted truth: a different body below a threshold, an exactly-GEV tail above.
#
#   F(x) = F_GEV(x)                          for x >= u
#   F(x) = F_GEV(u) * B(x) / B(u)            for x <  u
#
# with B a body cdf. Above u the truth IS the GEV, exactly -- so the fitted
# family is correctly specified in the tail and the tail-focused estimators are
# exactly consistent there, while the body can be made arbitrarily hostile to a
# global fit.
#
# The hydrological reading is the standard mixed-population one: above u every
# annual maximum is generated by the heavy mechanism (rain-on-snow), below it by
# a different and much less variable one (ordinary snowmelt, bounded by how much
# snowpack there is). Unlike max(GEV, Normal), where the GEV component still
# shapes the upper body and so leaks tail information into it, a graft lets the
# body carry no information about the tail at all -- which is what makes a global
# fit fail hard.
#
# The body used here is a normal truncated above at u, with its scale solved so
# that the density is continuous at the join.
# ---------------------------------------------------------------------------

graft_body_scale <- function(a, u, mu, sigma, xi, branch = c("wide", "tight")) {
  # Solve for b so that  F_GEV(u) * dnorm(u,a,b)/pnorm(u,a,b) = f_GEV(u), i.e.
  # the density is continuous at the join. The left-hand side rises then falls
  # in b, so there are two solutions: a "tight" body (small b, concentrated well
  # below the join) and a "wide" one (large b, reaching up to it).
  branch <- match.arg(branch)
  target <- dgev(u, mu, sigma, xi)
  f <- function(b) pgev(u, mu, sigma, xi) * dnorm(u, a, b) / pnorm(u, a, b) - target
  peak <- optimize(f, c(1e-6, 200), maximum = TRUE)$maximum
  if (f(peak) < 0) stop("no continuous-density body at this offset; move a closer to u")
  if (branch == "tight") uniroot(f, c(1e-8, peak), tol = 1e-13)$root
  else                   uniroot(f, c(peak, 1e4), tol = 1e-13)$root
}

make_graft <- function(mu, sigma, xi, p_join, a_offset, branch = "wide") {
  u <- qgev(p_join, mu, sigma, xi)
  a <- u - a_offset                       # body centre, below the join
  b <- graft_body_scale(a, u, mu, sigma, xi, branch)
  list(mu = mu, sigma = sigma, xi = xi, u = u, a = a, b = b, branch = branch,
       Fu = pgev(u, mu, sigma, xi), Pu = pnorm(u, a, b))
}

p_graft <- function(x, tr) {
  ifelse(x >= tr$u, pgev(x, tr$mu, tr$sigma, tr$xi),
         tr$Fu * pnorm(x, tr$a, tr$b) / tr$Pu)
}

d_graft <- function(x, tr) {
  ifelse(x >= tr$u, dgev(x, tr$mu, tr$sigma, tr$xi),
         tr$Fu * dnorm(x, tr$a, tr$b) / tr$Pu)
}

r_graft <- function(n, tr) {
  tail <- runif(n) >= tr$Fu
  out <- numeric(n)
  # tail draws: the GEV conditioned above u
  nt <- sum(tail)
  if (nt) out[tail] <- qgev(tr$Fu + runif(nt) * (1 - tr$Fu), tr$mu, tr$sigma, tr$xi)
  # body draws: the normal truncated above at u
  nb <- n - nt
  if (nb) out[!tail] <- qnorm(runif(nb) * tr$Pu, tr$a, tr$b)
  out
}

q_graft <- function(p, tr) {
  vapply(p, function(pp) {
    if (pp >= tr$Fu) return(qgev(pp, tr$mu, tr$sigma, tr$xi))
    qnorm(pp / tr$Fu * tr$Pu, tr$a, tr$b)
  }, numeric(1))
}

mean_graft <- function(tr) {
  gl <- gauss_legendre_01(600); s <- gl$x; u <- 1 - s^3
  sum(gl$w * q_graft(u, tr) * 3 * s^2)
}
